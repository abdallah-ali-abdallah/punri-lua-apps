local root = assert(arg[1], "Pass the calculations directory")
local B = dofile(root .. "/bigint.lua")
local D = dofile(root .. "/decimal.lua")(B)
local N = dofile(root .. "/number.lua")(B, D)
assert(math.maxinteger == 2147483647, "Use PUNRI's 32-bit Lua")
assert(16777216.0 + 1.0 == 16777216.0, "Use PUNRI's binary32 Lua")
local count = 0
local function equal(actual, expected)
    assert(actual == expected, "Expected " .. expected .. "; got " .. actual)
    count = count + 1
end
equal(B.mul("999999999999999999", "999999999999999999"), "999999999999999998000000000000000001")
equal(B.div("999999999999999998000000000000000001", "999999999999999999"), "999999999999999999")
equal(N.format(N.add(N.parse("0.1"), N.parse("0.2")), "fraction"), "3/10")
equal(N.format(N.sub(N.add(N.parse("1e8"), N.parse("1")), N.parse("1e8"))), "1")
equal(N.format(N.add(N.div(N.parse("1"), N.parse("3")), N.div(N.parse("1"), N.parse("6"))), "fraction"), "1/2")
equal(D.format(D.sqrt(D.parse("2"))), "1.41421356237")
equal(D.format(D.ln(D.parse("2"))), "0.69314718056")
equal(D.format(D.exp(D.parse("1"))), "2.71828182846")
local sine, cosine = D.sincos(D.parse("1"))
equal(D.format(sine), "0.841470984808")
equal(D.format(cosine), "0.540302305868")
equal(D.format(D.atan(D.parse("1"))), "0.785398163397")
equal(D.format(D.asin(D.parse("0.5"))), "0.523598775598")
equal(D.format(D.acos(D.parse("0.5"))), "1.0471975512")
equal(D.format(D.exp(D.parse("-10"))), "0.0000453999297625")
equal(D.format(D.ln(D.parse("1e-40"))), "-92.1034037198")
equal(D.format(D.sqrt(D.parse("1e-80"))), "1e-40")
print("PASS precision " .. count .. " vectors on signed32/binary32 Lua")
