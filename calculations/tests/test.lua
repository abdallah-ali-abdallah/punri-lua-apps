local root = assert(arg[1])
local B = dofile(root .. "/bigint.lua")
local D = dofile(root .. "/decimal.lua")(B)
local N = dofile(root .. "/number.lua")(B, D)
local P = dofile(root .. "/parser.lua")
local E = dofile(root .. "/engine.lua")(B, D, N, P)
local Editor = dofile(root .. "/editor.lua")(P)
local Tools = dofile(root .. "/tools.lua")(B, D, N, E, P)
local Store = dofile(root .. "/storage.lua")
assert(math.maxinteger == 2147483647 and 16777216.0 + 1.0 == 16777216.0, "Test with PUNRI Lua32")
local count = 0
local function check(ok, message) assert(ok, message); count = count + 1 end
local function run(source, expected, mode, context)
    local value, problem = E.run(source, context or {angle = "RAD"})
    check(value ~= nil, source .. ": " .. tostring(problem))
    check(N.format(value, mode) == expected, source .. ": " .. N.format(value, mode) .. " ~= " .. expected)
end
run("(3/4+5/8)*16", "22")
run("1/3+1/6", "1/2", "fraction")
run("0.1+0.2", "3/10", "fraction")
run("(10^8+1)-10^8", "1")
run("12345678901234567890+1", "12345678901234567891", "fraction")
run("-2^2", "-4")
run("(-2)^2", "4")
run("2^3^2", "512")
run("2^-3", "1/8", "fraction")
run("sqrt(9/16)", "3/4", "fraction")
run("root(3,-8)", "-2")
run("logbase(2,8)", "3")
run("sin(30)", "0.5", nil, {angle = "DEG"})
run("sin(pi/6)", "0.5")
run("cos(pi)", "-1")
run("tan(pi/4)", "1")
run("asin(0.5)", "30", nil, {angle = "DEG"})
run("acos(0.5)", "60", nil, {angle = "DEG"})
run("atan(1)", "45", nil, {angle = "DEG"})
run("5!", "120")
run("gcd(48,18)", "6")
run("lcm(12,18)", "36")
run("sqrt(2)", "1.41421356237")
run("ln(2)", "0.69314718056")
run("exp(1)", "2.71828182846")
run("sinh(1e-30)", "1e-30")
run("cosh(1e-30)", "1")
run("tanh(100)", "1")
run("A+Ans", "5", nil, {variables = {A = N.parse("2")}, ans = N.parse("3")})
for _, source in ipairs({"1/0", "sqrt(-1)", "ln(0)", "root(0,3)", "root(2,-1)", "tan(90)", "100!", "1e99", "sin(1,2)", "gcd(1/2,3)", "load(1)", "?", "(1+2", "2(3)", "x=1=2", "1;os.exit()", "1+"}) do
    local value = E.run(source, {angle = "DEG"})
    check(not value, "Expected failure: " .. source)
end
local e = Editor.new()
check(Editor.template(e, "fraction"), "Insert fraction")
check(e.source == "(?)/(?)" and e.p == 2 and e.q == 3, "Numerator selected")
Editor.key(e, "3"); Editor.move(e, 1); Editor.key(e, "4")
check(e.source == "(3)/(4)", "Fill numerator and denominator")
Editor.move(e, 1); Editor.key(e, "+"); Editor.key(e, "1")
check(e.source == "(3)/(4)+1", "Next field exits a completed fraction before an operator")
Editor.set(e, "(3)/(4)"); e.p, e.q = 7, 7
Editor.move(e, -1); Editor.template(e, "root")
check(e.source == "(sqrt(3))/(4)", "Wrap selected value with root")
Editor.history(e, false); check(e.source == "(3)/(4)", "Undo template")
Editor.history(e, true); check(e.source == "(sqrt(3))/(4)", "Redo template")
Editor.set(e, ""); Editor.template(e, "equation"); Editor.key(e, "x"); Editor.template(e, "power"); Editor.key(e, "2"); Editor.move(e, 1); Editor.key(e, "9")
check(e.source == "(x)^(2)=9", "Natural equation entry")
check(P.parse(e.source).k == "eq", "Equation tree")
check(not Editor.set(e, "1|2\nchecksum|bad"), "Reject record injection")
Editor.set(e, "3/4"); Editor.template(e, "power"); check(e.source == "(3/4)^(?)", "Power wraps a complete fraction")
Editor.set(e, "2+3"); Editor.template(e, "power"); check(e.source == "2+(3)^(?)", "Power wraps the last sum operand")
Editor.set(e, "sqrt(9)"); Editor.template(e, "fraction"); check(e.source == "(sqrt(9))/(?)", "Fraction wraps a function call")
check(not P.parse(string.rep("(", 21) .. "1" .. string.rep(")", 21)), "Depth limit")
local stats = Tools.statistics("2,4,4,4,5,5,7,9")
check(stats[2][2] == "5" and stats[3][2] == "4.5" and stats[4][2] == "2", "Stable statistics")
check(Tools.matrix("2,1,0;0,3,1;0,0,4", "determinant")[1][2] == "24", "Determinant")
check(Tools.matrix("1,2;3,4", "inverse")[1][2] == "-2, 1", "Inverse")
check(not pcall(Tools.matrix, "1,2;2,4", "inverse"), "Singular inverse")
check(Tools.complex("3,4", "DEG")[3][2] == "5", "Complex magnitude")
check(Tools.base("FFFFFFFF", 16)[3][2] == "4294967295", "Unsigned 32-bit maximum")
check(not pcall(Tools.base, "100000000", 16), "Unsigned overflow")
check(Tools.convert("1", 1, 5, 2)[1][2] == "2.54 cm", "Exact inch conversion")
check(Tools.convert("-40", 3, 1, 2)[1][2] == "-40 F", "Temperature")
local job = Tools.solver("x^2=2", "0", "2", {angle = "RAD"})
for _ = 1, 60 do if job.done then break end; Tools.solve_step(job) end
check(job.done and N.format(job.root) == "1.41421356237", "Bracketed solver")
check(not pcall(Tools.solver, "x^2+1=0", "-1", "1", {}), "Reject no bracket")
local pole = Tools.solver("1/x=0", "-1", "2", {})
local ok = pcall(function() for _ = 1, 60 do if pole.done then break end; Tools.solve_step(pole) end end)
check(not ok or not pole.done, "A pole is never a root")
local state = {angle = "DEG", mode = "fraction", locale = "en", orientation = "portrait", view = "calculate", editor = e,
    ans = N.parse("0.5"), evaluated = "1/2", variables = {A = N.parse("1234567890123")}, history = {{source = "1/2", answer = "1/2", angle = "RAD"}},
    functions = {{source = "x^2", enabled = true}, {source = "x", enabled = false}, {source = "", enabled = false}, {source = "", enabled = false}}}
local serialized = assert(Store.encode(state, N))
local restored, problem = Store.decode(serialized, N, P)
check(restored and restored.input == e.source and restored.mode == "fraction", "Session round trip: " .. tostring(problem))
check(not Store.decode(serialized:gsub("1/2", "1/3", 1), N, P), "Checksum detects damage")
check(not Store.decode(serialized:gsub("CALCULATIONS_1", "CALCULATIONS_2", 1), N, P), "Unknown schema")
print("PASS " .. count .. " engine/editor/tools/storage checks on Lua32")
