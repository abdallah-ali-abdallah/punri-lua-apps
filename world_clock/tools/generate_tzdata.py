#!/usr/bin/env python3
"""Generate World Clock's bounded transition data from a pinned IANA tzdata tree.

Run this only on a development machine.  The device reads the resulting small
text file, never binary zoneinfo.  UTC instants are stored as minutes since
2000-01-01 so Lua's 32-bit numeric build never evaluates a post-2038 Unix
timestamp.  A separate Lua vector file is emitted for host tests; it contains
literal expected results and is not read by the application.
"""

from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path
from zoneinfo import ZoneInfo, reset_tzpath


START_YEAR = 2024
END_YEAR = 2040
BASE = dt.datetime(2000, 1, 1, tzinfo=dt.timezone.utc)
START = dt.datetime(START_YEAR, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(END_YEAR + 1, 1, 1, tzinfo=dt.timezone.utc)
ZONES = [
    "Africa/Cairo", "Europe/London", "Europe/Paris", "America/New_York", "America/Toronto",
    "America/Los_Angeles", "America/Sao_Paulo", "America/Mexico_City", "America/St_Johns",
    "Asia/Dubai", "Asia/Riyadh", "Asia/Kolkata", "Asia/Kathmandu", "Asia/Bangkok", "Asia/Singapore",
    "Asia/Tokyo", "Australia/Sydney",
]
VECTOR_UTC = [
    ("America/New_York", (2024, 3, 10, 6, 59)), ("America/New_York", (2024, 3, 10, 7, 0)),
    ("America/New_York", (2024, 3, 10, 7, 1)), ("America/New_York", (2024, 11, 3, 5, 59)),
    ("America/New_York", (2024, 11, 3, 6, 0)), ("America/New_York", (2024, 11, 3, 6, 1)),
    ("Europe/London", (2024, 3, 31, 0, 59)), ("Europe/London", (2024, 3, 31, 1, 0)),
    ("Europe/London", (2024, 3, 31, 1, 1)), ("Europe/London", (2024, 10, 27, 0, 59)),
    ("Europe/London", (2024, 10, 27, 1, 0)), ("Europe/London", (2024, 10, 27, 1, 1)),
    ("Australia/Sydney", (2024, 4, 6, 15, 59)), ("Australia/Sydney", (2024, 4, 6, 16, 0)),
    ("Australia/Sydney", (2024, 4, 6, 16, 1)), ("Australia/Sydney", (2024, 10, 5, 15, 59)),
    ("Australia/Sydney", (2024, 10, 5, 16, 0)), ("Australia/Sydney", (2024, 10, 5, 16, 1)),
    ("Africa/Cairo", (2024, 4, 25, 21, 59)), ("Africa/Cairo", (2024, 4, 25, 22, 0)),
    ("Africa/Cairo", (2024, 10, 31, 20, 59)), ("Africa/Cairo", (2024, 10, 31, 21, 0)),
    ("Asia/Kolkata", (2024, 2, 29, 12, 0)), ("Asia/Kathmandu", (2024, 2, 29, 12, 0)),
    ("America/St_Johns", (2024, 1, 1, 4, 0)), ("America/New_York", (2024, 1, 1, 2, 0)),
    ("Asia/Tokyo", (2024, 12, 31, 23, 30)),
]


def minutes(instant: dt.datetime) -> int:
    return int((instant - BASE).total_seconds() // 60)


def state(zone: ZoneInfo, instant: dt.datetime) -> tuple[int, bool]:
    local = instant.astimezone(zone)
    offset = int(local.utcoffset().total_seconds() // 60)
    return offset, bool(local.dst() and local.dst().total_seconds())


def find_transitions(zone: ZoneInfo) -> tuple[tuple[int, bool], list[tuple[int, int, bool]]]:
    initial = state(zone, START)
    previous = initial
    cursor = START
    transitions: list[tuple[int, int, bool]] = []
    # Every selected-zone transition is separated by much more than six hours.
    # The binary search narrows the known state change to its first UTC minute.
    while cursor < END:
        probe = min(cursor + dt.timedelta(hours=6), END)
        next_state = state(zone, probe)
        if next_state != previous:
            low, high = cursor, probe
            while (high - low) > dt.timedelta(minutes=1):
                middle = low + (high - low) // 2
                if state(zone, middle) == previous:
                    low = middle
                else:
                    high = middle
            transitions.append((minutes(high), next_state[0], next_state[1]))
        cursor, previous = probe, next_state
    return initial, transitions


def utc_from_tuple(value: tuple[int, int, int, int, int]) -> dt.datetime:
    return dt.datetime(*value, tzinfo=dt.timezone.utc)


def generate_zones(output: Path, version: str) -> None:
    lines = [
        "# Generated by tools/generate_tzdata.py; do not hand-edit.",
        f"# IANA tzdata {version}; UTC transition minutes since 2000-01-01.",
        f"# Supported UTC civil range: {START_YEAR}-01-01 through {END_YEAR}-12-31.",
        "",
    ]
    for name in ZONES:
        zone = ZoneInfo(name)
        initial, transitions = find_transitions(zone)
        lines.append(f"[{name}]")
        lines.append(f"b={initial[0]},{1 if initial[1] else 0}")
        lines.extend(f"t={at},{offset},{1 if dst else 0}" for at, offset, dst in transitions)
        lines.append("")
    output.write_text("\n".join(lines), encoding="ascii")


def generate_vectors(output: Path, version: str) -> None:
    lines = [
        f"-- Fixed expected results from IANA tzdata {version}; generated outside the Lua runtime.",
        "-- These are independent oracle values for test/lua_apps/world_clock_scenarios.lua.",
        "return {",
    ]
    for name, value in VECTOR_UTC:
        instant = utc_from_tuple(value)
        local = instant.astimezone(ZoneInfo(name))
        offset, dst = state(ZoneInfo(name), instant)
        lines.append(
            "  {zone=%r, utc={year=%d,month=%d,day=%d,hour=%d,min=%d}, "
            "local_time={year=%d,month=%d,day=%d,hour=%d,min=%d}, offset=%d, dst=%s},"
            % (name, *value, local.year, local.month, local.day, local.hour, local.minute, offset, "true" if dst else "false")
        )
    lines.append("}")
    output.write_text("\n".join(lines) + "\n", encoding="ascii")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--tzdir", type=Path, required=True, help="Directory produced by zic from the pinned IANA release")
    parser.add_argument("--version", required=True, help="Pinned IANA tzdata label, for example 2026d")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "zones.txt")
    parser.add_argument("--vectors", type=Path, required=True)
    args = parser.parse_args()
    reset_tzpath([str(args.tzdir)])
    generate_zones(args.output, args.version)
    generate_vectors(args.vectors, args.version)


if __name__ == "__main__":
    main()
